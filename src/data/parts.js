export function partById(cat, id) {
  return PARTS[cat].find((p) => p.id === id) || PARTS[cat][0];
}
export function asmParts(asm) {
  return {
    head: partById('head', asm.head),
    core: partById('core', asm.core),
    arms: partById('arms', asm.arms),
    legs: partById('legs', asm.legs),
    booster: partById('booster', asm.booster),
    generator: partById('generator', asm.generator),
    fcs: partById('fcs', asm.fcs),
    rarm: partById('arm', asm.rarm),
    larm: partById('arm', asm.larm),
    rback: partById('back', asm.rback),
    lback: partById('back', asm.lback),
  };
}
export function asmStats(asm) {
  const p = asmParts(asm);
  const weight =
    p.head.weight +
    p.core.weight +
    p.arms.weight +
    p.legs.weight +
    p.booster.weight +
    p.generator.weight +
    p.fcs.weight +
    p.rarm.weight +
    p.larm.weight +
    p.rback.weight +
    p.lback.weight;
  const enLoad =
    p.head.en +
    p.core.en +
    p.arms.en +
    p.legs.en +
    p.booster.en +
    p.fcs.en +
    p.rarm.en +
    p.larm.en +
    p.rback.en +
    p.lback.en;
  const ap = p.head.ap + p.core.ap + p.arms.ap + p.legs.ap;
  const stab = p.head.stab + p.core.stab + p.arms.stab + p.legs.stab;
  const wRatio = weight / p.legs.load;
  const speed = p.legs.speed * p.booster.thrust * (1.15 - 0.35 * Math.min(1, wRatio));
  const enOut = p.generator.output;
  return {
    parts: p,
    weight,
    load: p.legs.load,
    enLoad,
    enOut,
    ap,
    stab,
    speed,
    jump: p.legs.jumpH,
    enCap: p.generator.cap,
    overWeight: weight > p.legs.load,
    overEn: enLoad > enOut,
    def: p.core.def,
    lockRange: p.fcs.range * (p.head.id === 'h_scan' ? 1.15 : 1),
  };
}

// ---- 跳躍與懸浮（MechEntity.jumpMove、車庫顯示）----
// 腳部的 jumpH／jumpT：地面跳的高度（m）與到頂時間（s）；airH／airT：空中跳（第 1 次）；airN：空中跳次數。
// 上升時用各自的重力（2h/t²），過了最高點一律用 GRAVITY 下落；連續的空中跳高度依 AIR_DECAY 遞減
export const GRAVITY = 42;
export const JUMP_EN = 40; // 地面跳躍的耗能
export const AIR_DECAY = [1, 0.75, 0.55];
// 失衡後保護（只給玩家，MechEntity.pilotEnt）：硬直結束後這段時間內 ACS 只累積 STAG_GUARD_K 倍、最多到 STAG_GUARD_CAP，近戰連段與 EMP 也不會再讓它失衡
export const STAG_GUARD = 3.5;
export const STAG_GUARD_K = 0.3;
export const STAG_GUARD_CAP = 0.9;
// PvE 的玩家機體（pilotEnt、不是 PvP）：承受的衝擊倍率、ACS 開始回復前的等待（秒）
export const PVE_IMP_K = 0.65;
export const PVE_ACS_DELAY = 0.6;
// 一般敵人（不是 Boss）：失衡門檻倍率、硬直時間
export const FOE_STAB_K = 0.75;
export const FOE_STAG_T = 2.6;
export function jumpSpec(legs) {
  const t = legs.type;
  let maxH = legs.jumpH;
  for (let i = 0; i < legs.airN; i++) maxH += legs.airH * AIR_DECAY[Math.min(i, AIR_DECAY.length - 1)];
  return {
    v: (2 * legs.jumpH) / legs.jumpT,
    g: (2 * legs.jumpH) / (legs.jumpT * legs.jumpT),
    height: legs.jumpH,
    airH: legs.airH,
    airG: (2 * legs.airH) / (legs.airT * legs.airT),
    air: legs.airN,
    maxH,
    canHover: t !== 'tank',
    hover: t === 'quad' ? 50 : 240,
    climb: t === 'quad' ? 240 : 480,
    freeHover: t === 'quad',
  };
}
