// 經驗 → 等級（1～10）
export function heroLvOf(xp) {
  let lv = 1;
  while (lv < RTS_HERO_LV_MAX && xp >= RTS_HERO_XP[lv]) lv++;
  return lv;
}
// 技能某一級的數值（lv 1 起；0＝還沒學）
export function skillLv(id, lv) {
  const S = RTS_SKILLS[id];
  if (!S || !lv) return null;
  return S.lv[Math.min(lv, S.lv.length) - 1];
}
