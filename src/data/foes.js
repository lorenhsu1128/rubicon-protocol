// 主題的專屬敵人（depth：垂直主題的深度）
export function themeFoes(theme, depth = 0) {
  return Object.keys(FOES).filter(
    (k) => FOES[k].theme === theme && (FOES[k].depth || 0) <= depth && !FOES[k].spawnOnly,
  );
}
