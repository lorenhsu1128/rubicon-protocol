// 依抉擇的文字：陣列的項目是字串，或 { 抉擇 id: { 選項: 字串或字串陣列 } }（沒選過的略過）
export function pickLines(lines, choices = {}) {
  const out = [];
  for (const l of lines || []) {
    if (typeof l === 'string') {
      out.push(l);
      continue;
    }
    for (const k in l) {
      const v = l[k][choices[k]];
      if (Array.isArray(v)) out.push(...v);
      else if (v) out.push(v);
    }
  }
  return out;
}
// 簡報的委託方：字串，或 { 抉擇 id: { 選項: 委託方 } }（還沒選時用第一個）
export function briefClient(B, choices = {}) {
  const c = B && B.client;
  if (!c || typeof c === 'string') return c || 'castron';
  for (const k in c) return c[k][choices[k]] || Object.values(c[k])[0];
  return 'castron';
}

